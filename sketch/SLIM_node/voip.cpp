bool voipBegin() {
  for (int i = 0; i < 256; i++) ulawDecodeTable[i] = ulawToLinear(i);

  // ---- WiFi ----
  WiFi.mode(WIFI_STA);
  String myMac = WiFi.macAddress();
  Serial.print(F("WiFi MAC address: "));
  Serial.println(myMac);
  for (int i = 0; i < DIRN; i++) {
    if (DIR[i].mac.length() && myMac.equalsIgnoreCase(DIR[i].mac.c_str())) {
      myEntry = i;
      break;
    }
  }

  Serial.print(F("Connecting to WiFi "));
  Serial.print(settings.wifiSsid);
  bool connected = false;
  if (settings.wifiSsid.length()) {
    wifiStart();
    for (int attempts = 0; attempts < VOIP_WIFI_CONNECT_SECONDS; attempts++) {
      if (WiFi.status() == WL_CONNECTED) { connected = true; break; }
      Serial.print(".");
      delay(1000);
    }
  }
  if (connected) {
    digitalWrite(LED_BUILTIN, HIGH);             // show WiFi connected on ESP32 module LED
    Serial.print(F("\r\nIP address: "));
    Serial.println(WiFi.localIP());
  } else {
    startAccessPoint();
  }

  if (settings.myNumber.length()) {              // number set on the config page / voip_config.h
    localPhoneNumber = settings.myNumber;
  } else {
    if (myEntry < 0 && connected) {              // no MAC match: identify by our IP address
      String myIp = WiFi.localIP().toString();
      for (int i = 0; i < DIRN; i++)
        if (myIp == DIR[i].ip) myEntry = i;
    }
    if (myEntry >= 0) localPhoneNumber = DIR[myEntry].number;
  }
  if (localPhoneNumber.length()) {
    Serial.print(F("This phone's number: "));
    Serial.println(localPhoneNumber);
    if (!apMode) {                               // also reachable as http://slim-<number>.local/
      String host = String("slim-") + localPhoneNumber;
      if (MDNS.begin(host.c_str())) MDNS.addService("http", "tcp", 80);
    }
  } else {
    Serial.println(F("*** This phone's number isn't set and its IP/MAC isn't in the directory. It can call out but can't be called."));
  }

  // ---- UDP sockets ----
  sock = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
  sockaddr_in local;
  memset(&local, 0, sizeof(local));
  local.sin_family = AF_INET;
  local.sin_port = htons(VOIP_UDP_PORT);
  local.sin_addr.s_addr = htonl(INADDR_ANY);
  if (sock < 0 || bind(sock, (sockaddr*)&local, sizeof(local)) < 0) {
    Serial.println(F("[voip] could not open UDP port"));
    return false;
  }
  int yes = 1;
  setsockopt(sock, SOL_SOCKET, SO_BROADCAST, &yes, sizeof(yes));   // phone line calls find the far node by broadcast
  fcntl(sock, F_SETFL, fcntl(sock, F_GETFL, 0) | O_NONBLOCK);
  audioTxSock = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);

  // ---- audio capture: ADC1 channel 4 (GPIO32) ----
  adc1_config_width(ADC_WIDTH_BIT_12);
#if   VOIP_ADC_ATTEN_DB == 0
  adc1_config_channel_atten(MIC_ADC_CHANNEL, (adc_atten_t)0);   // 0 dB:   ~0.1 - 0.95 V
#elif VOIP_ADC_ATTEN_DB == 2
  adc1_config_channel_atten(MIC_ADC_CHANNEL, (adc_atten_t)1);   // 2.5 dB: ~0.1 - 1.25 V
#elif VOIP_ADC_ATTEN_DB == 6
  adc1_config_channel_atten(MIC_ADC_CHANNEL, (adc_atten_t)2);   // 6 dB:   ~0.15 - 1.75 V
#else
  adc1_config_channel_atten(MIC_ADC_CHANNEL, (adc_atten_t)3);   // 11 dB:  ~0.15 - 2.45 V
#endif

  txQueue = xQueueCreate(8, sizeof(AudioFrame));
  loopQueue = xQueueCreate(8, sizeof(AudioFrame));
  dtmfQueue = xQueueCreate(8, sizeof(char));
  // highest priority on core 0 so WiFi processing can't delay (jitter) the ADC samples
  xTaskCreatePinnedToCore(captureTask, "voipCapture", 4096, NULL, configMAX_PRIORITIES - 1, &captureTaskHandle, 0);
  xTaskCreatePinnedToCore(senderTask,  "voipSend",    4096, NULL, 5,  &senderTaskHandle,  0);
  while (sampleTimer == NULL) delay(1);          // wait for capture task to set up its timer
  return true;
}

void voipPoll() {
  runTxSource();                                 // voicemail audio is timing critical: check every pass
  runLocalPlayback();

  unsigned long nowUs = micros();
  if (nowUs - lastPollUs < POLL_INTERVAL_US) return;   // keep loop() fast for Mozzi
  lastPollUs = nowUs;

  if (apMode) {
    if (dnsServer) dnsServer->processNextRequest();
    digitalWrite(LED_BUILTIN, (millis() / 500) & 1);   // blinking: access point mode
  } else {
    digitalWrite(LED_BUILTIN, WiFi.status() == WL_CONNECTED);
  }
  if (sock < 0) return;

  uint8_t buf[MAX_PACKET + 16];
  for (int n = 0; n < 16; n++) {                 // drain everything that has arrived
    sockaddr_in src;
    socklen_t srcLen = sizeof(src);
    int len = recvfrom(sock, buf, sizeof(buf), 0, (sockaddr*)&src, &srcLen);
    if (len <= 0) break;
    handlePacket(buf, len, src);
  }

  // frames looped back from our own microphone: echo test or local recording
  AudioFrame lf;
  while (loopQueue && xQueueReceive(loopQueue, &lf, 0) == pdTRUE) {
    if (loopRoute == LR_ECHO && sess == SS_CONNECTED) {
      sessLastRxMs = millis();
      handleAudioPayload(lf.seq, lf.data, VOIP_FRAME_SAMPLES);
    } else if (loopRoute == LR_LOCALMIC && localMicFn) {
      localMicFn(lf.data, VOIP_FRAME_SAMPLES);
    }
  }

  runTimers();
  printStats();
  printScan();
}

