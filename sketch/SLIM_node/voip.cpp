// run the sample timer only while dialing or capturing audio
static void updateSampleTimer() {
  bool want = mediaActive || dialListen;
  if (want == timerRunning || sampleTimer == NULL) return;
  timerRunning = want;
  if (want) {
    timerWrite(sampleTimer, 0);
    timerAlarmEnable(sampleTimer);
  } else {
    timerAlarmDisable(sampleTimer);
  }
}

static void startMedia() {
  jbReset();
  jbLocal = false;
  resetPlaybackStats();
  statsLastMs = millis();
  sessGotAudio = false;
  portENTER_CRITICAL(&mediaMux);
  mediaCallId = sessCallId;
  mediaPeer = sessPeer;
  portEXIT_CRITICAL(&mediaMux);
  farEndLevel = 0;
  txSeq = 0;
  mediaGeneration = mediaGeneration + 1;
  mediaActive = true;
  specState = SPEC_FILLING;
  updateSampleTimer();
}

static void stopMedia() {
  mediaActive = false;
  updateSampleTimer();
  jbReset();
  xQueueReset(loopQueue);
}

