/*
  voip.cpp
  Phone calls between SLIM nodes over WiFi.  See voip.h.

  Threading:
    - loop() task (core 1): voipPoll() receives all UDP packets, runs call
      signaling, fills the playback jitter buffer, and sends audio generated by
      voicemail.  Mozzi's updateAudio() (also called from loop) empties the
      jitter buffer.  Because both happen in the same task it needs no locking.
    - capture task (core 0): woken 8192 times/sec by a hardware timer, reads
      the SLIC audio on GPIO32, filters it, decodes DTMF, u-law encodes it, and
      queues 160 sample frames.
    - sender task (core 0): sends the queued audio frames to the far end (or
      back to the loop task for the echo test and local recording).
*/

