enum PacketType : uint8_t {
  PKT_INVITE = 1,      // caller -> callee: please ring your phone (resent while waiting)
  PKT_RINGING,         // callee -> caller: phone is ringing
  PKT_BUSY,            // callee -> caller: can't take the call
  PKT_ANSWER,          // callee -> caller: phone answered
  PKT_HANGUP,          // either way: call ended
  PKT_AUDIO,           // either way: u-law audio frame
  PKT_KEEPALIVE        // either way: still connected
};

struct __attribute__((packed)) PacketHeader {
  char     magic[2];   // 'S','L'
  uint8_t  version;
  uint8_t  type;
  uint32_t callId;     // random id chosen by the caller for each call
  uint16_t seq;        // audio frame sequence number
  uint16_t len;        // payload length
};

#define INV_TRUNK      0x01   // call uses the phone line, no audio packets
#define INV_BROADCAST  0x02   // sent to every node; only the one with the number answers

struct __attribute__((packed)) InvitePayload {
  char    from[16];    // caller's phone number
  char    to[16];      // number dialed
  uint8_t flags;
};

