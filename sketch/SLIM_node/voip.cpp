// signaling
// ---------------------------------------------------------------------------
static void sendControl(PacketType type, uint32_t callId, const sockaddr_in& to,
                        const void* payload = NULL, uint16_t len = 0) {
  uint8_t pkt[sizeof(PacketHeader) + sizeof(InvitePayload)];
  PacketHeader* h = (PacketHeader*)pkt;
  h->magic[0] = 'S';
  h->magic[1] = 'L';
  h->version = PROTOCOL_VERSION;
  h->type = type;
  h->callId = callId;
  h->seq = 0;
  h->len = len;
  if (len) memcpy(pkt + sizeof(PacketHeader), payload, len);
  sendto(sock, pkt, sizeof(PacketHeader) + len, 0, (const sockaddr*)&to, sizeof(to));
  sessLastTxMs = millis();
}

static void sendInvite() {
  InvitePayload inv;
  memset(&inv, 0, sizeof(inv));
  strncpy(inv.from, localPhoneNumber.c_str(), sizeof(inv.from) - 1);
  strncpy(inv.to, sessDialedNumber.c_str(), sizeof(inv.to) - 1);
  inv.flags = (sessTrunk ? INV_TRUNK : 0) | (sessPeerBroadcast ? INV_BROADCAST : 0);
  sendControl(PKT_INVITE, sessCallId, sessPeer, &inv, sizeof(inv));
}

static void setEvent(VoipEvent ev) {
  pendingEvent = ev;
}

static void endSession() {
  stopMedia();
  sess = SS_IDLE;
  sessCallId = 0;
  sessTrunk = false;
  sessPeerBroadcast = false;
  loopRoute = LR_NETWORK;
  txSourceFn = NULL;
  txFromLoop = false;
  rxSinkFn = NULL;
  if (radioOffTest) {                            // echo test turned the radio off: reconnect
    radioOffTest = false;
    Serial.println(F("[voip] WiFi radio back on, reconnecting"));
    wifiStart();
  }
}

// does this packet belong to the call in progress?
static bool fromPeer(const sockaddr_in& src, uint32_t callId) {
  if (sess == SS_IDLE || callId != sessCallId) return false;
  if (sessPeerBroadcast) {                       // first reply to a broadcast call: that's the far end
    sessPeer = src;
    sessPeer.sin_port = htons(VOIP_UDP_PORT);
    sessPeerBroadcast = false;
    Serial.printf("[voip] %s answered from %s\r\n", sessDialedNumber.c_str(), inet_ntoa(src.sin_addr));
    return true;
  }
  return src.sin_addr.s_addr == sessPeer.sin_addr.s_addr;
}

static void connectCall() {
  sess = SS_CONNECTED;
  sessLastRxMs = millis();
  if (!sessTrunk) startMedia();                  // phone line calls: the relay carries the audio
  setEvent(VOIP_EV_ANSWERED);
  Serial.println(sessTrunk ? F("[voip] call connected over the phone line") : F("[voip] call connected"));
}

// accept an incoming INVITE as the session
static void takeInvite(const PacketHeader* h, const InvitePayload& inv, const sockaddr_in& src) {
  sess = SS_IN_RINGING;
  sessCallId = h->callId;
  sessPeer = src;
  sessPeer.sin_port = htons(VOIP_UDP_PORT);
  sessPeerBroadcast = false;
  sessTrunk = (inv.flags & INV_TRUNK) != 0;
  sessPeerNumber = inv.from;
  sessDialedNumber = "";
  sessStartMs = sessLastRxMs = millis();
  remotePhoneNum = inv.from;
}

static void handlePacket(const uint8_t* buf, int len, const sockaddr_in& src) {
  if (len < (int)sizeof(PacketHeader)) return;
  const PacketHeader* h = (const PacketHeader*)buf;
  if (h->magic[0] != 'S' || h->magic[1] != 'L' || h->version != PROTOCOL_VERSION) return;
  if ((int)(sizeof(PacketHeader) + h->len) > len) return;
  const uint8_t* payload = buf + sizeof(PacketHeader);
  unsigned long now = millis();

  if (h->type == PKT_INVITE) {
    if (h->len < sizeof(InvitePayload)) return;
    InvitePayload inv;
    memcpy(&inv, payload, sizeof(inv));
    inv.from[sizeof(inv.from) - 1] = 0;
    inv.to[sizeof(inv.to) - 1] = 0;
    bool broadcast = (inv.flags & INV_BROADCAST) != 0;

    if (localPhoneNumber.length() == 0 || localPhoneNumber != inv.to) {
      if (!broadcast) {                          // sent straight to us but not our number
        Serial.printf("[voip] call for %s arrived here (this is %s) - check the directory IPs\r\n",
                      inv.to, localPhoneNumber.c_str());
        sendControl(PKT_BUSY, h->callId, src);
      }
      return;                                    // broadcast for another node: ignore
    }
    if (sess != SS_IDLE && h->callId == sessCallId && src.sin_addr.s_addr == sessPeer.sin_addr.s_addr) {
      sessLastRxMs = now;                        // repeat of the call already in progress
      if (sess == SS_IN_RINGING) sendControl(PKT_RINGING, h->callId, src);
      else if (sess == SS_CONNECTED) sendControl(PKT_ANSWER, h->callId, src);  // our answer was lost
      return;
    }

    // both phones called each other at the same moment (eg. two Batphones picked
    // up together).  The node with the higher number gives up its own call and
    // answers the other one, so the two get connected instead of both busy.
    if ((sess == SS_OUT_INVITING || sess == SS_OUT_RINGING) && sessDialedNumber == inv.from) {
      if (localPhoneNumber > String(inv.from)) {
        for (int i = 0; i < 2; i++) sendControl(PKT_HANGUP, sessCallId, sessPeer);
        takeInvite(h, inv, src);
        sendControl(PKT_ANSWER, sessCallId, sessPeer);
        sendControl(PKT_ANSWER, sessCallId, sessPeer);
        Serial.println(F("[voip] both phones called each other - connecting"));
        connectCall();
      }
      return;                                    // lower number: wait for the other node to answer ours
    }

    if (sess != SS_IDLE || nodeBusy()) {
      sendControl(PKT_BUSY, h->callId, src);
      return;
    }
    // new incoming call
    takeInvite(h, inv, src);
    sendControl(PKT_RINGING, h->callId, src);
    setEvent(VOIP_EV_INCOMING);
    Serial.printf("[voip] incoming %scall from %s (%s)\r\n", sessTrunk ? "phone line " : "",
                  inv.from, inet_ntoa(src.sin_addr));
    return;
  }

  if (!fromPeer(src, h->callId)) return;         // everything else must belong to our call
  sessLastRxMs = now;

  switch (h->type) {
    case PKT_RINGING:
      if (sess == SS_OUT_INVITING) {
        sess = SS_OUT_RINGING;
        setEvent(VOIP_EV_RINGING);
        Serial.println(F("[voip] far end ringing"));
      }
      break;

    case PKT_BUSY:
      if (sess == SS_OUT_INVITING || sess == SS_OUT_RINGING) {
        endSession();
        setEvent(VOIP_EV_BUSY);
        Serial.println(F("[voip] far end busy"));
      }
      break;

    case PKT_ANSWER:
      if (sess == SS_OUT_INVITING || sess == SS_OUT_RINGING) connectCall();
      break;

    case PKT_HANGUP:
      endSession();
      setEvent(VOIP_EV_HANGUP);
      Serial.println(F("[voip] far end hung up"));
      break;

    case PKT_AUDIO:
      if (sess == SS_OUT_INVITING || sess == SS_OUT_RINGING) connectCall();   // answer packet was lost
      if (sess == SS_CONNECTED && !sessTrunk) handleAudioPayload(h->seq, payload, h->len);
      break;

    case PKT_KEEPALIVE:
      if ((sess == SS_OUT_INVITING || sess == SS_OUT_RINGING) && sessTrunk) connectCall();  // answer was lost
      break;
  }
}

static void runTimers() {
  unsigned long now = millis();
  switch (sess) {
    case SS_OUT_INVITING:
      if (now - sessStartMs > INVITE_GIVEUP_MS) {
        Serial.println(F("[voip] no answer from far end node"));
        endSession();
        setEvent(VOIP_EV_TIMEOUT);
      } else if (now - sessLastTxMs > INVITE_RESEND_MS) {
        sendInvite();
      }
      break;

    case SS_OUT_RINGING:
      if (now - sessLastRxMs > PEER_TIMEOUT_MS) {
        Serial.println(F("[voip] far end node stopped responding"));
        endSession();
        setEvent(VOIP_EV_TIMEOUT);
      } else if (now - sessLastTxMs > RINGING_KEEPALIVE_MS) {
        sendInvite();
      }
      break;

    case SS_IN_RINGING:
      if (now - sessLastRxMs > PEER_TIMEOUT_MS) {   // caller vanished without hanging up
        Serial.println(F("[voip] caller went away"));
        endSession();
        setEvent(VOIP_EV_HANGUP);
      }
      break;

    case SS_CONNECTED:
      if (loopRoute == LR_ECHO) break;           // echo test: no far end
      if (now - sessLastRxMs > PEER_TIMEOUT_MS) {
        Serial.println(F("[voip] lost contact with far end"));
        endSession();
        setEvent(VOIP_EV_TIMEOUT);
      } else if (now - sessLastTxMs > CONNECTED_KEEPALIVE_MS) {
        sendControl(PKT_KEEPALIVE, sessCallId, sessPeer);
      }
      break;

    default:
      break;
  }
}

// voicemail is sending: build and send audio frames from txSourceFn on time
static void runTxSource() {
  if (!txSourceFn || sess != SS_CONNECTED || sessTrunk) return;
  uint32_t now = micros();
  if ((int32_t)(now - txDueUs) > 200000) txDueUs = now;   // fell far behind: resync
  while ((int32_t)(now - txDueUs) >= 0) {
    int16_t pcm[VOIP_FRAME_SAMPLES];
    int n = txSourceFn(pcm, VOIP_FRAME_SAMPLES);
    if (n < 0) n = 0;
    for (int i = n; i < VOIP_FRAME_SAMPLES; i++) pcm[i] = 0;   // nothing to say: silence

    uint8_t pkt[MAX_PACKET];
    PacketHeader* h = (PacketHeader*)pkt;
    h->magic[0] = 'S';
    h->magic[1] = 'L';
    h->version = PROTOCOL_VERSION;
    h->type = PKT_AUDIO;
    h->callId = sessCallId;
    h->seq = txSeq;
    txSeq = txSeq + 1;
    h->len = VOIP_FRAME_SAMPLES;
    for (int i = 0; i < VOIP_FRAME_SAMPLES; i++) pkt[sizeof(PacketHeader) + i] = linearToUlaw(pcm[i]);
    sendto(sock, pkt, sizeof(PacketHeader) + VOIP_FRAME_SAMPLES, 0, (const sockaddr*)&sessPeer, sizeof(sessPeer));

    txDueUs += 19531;                            // 160 / 8192 sec = 19531.25 uS
    if (++txFrac >= 4) { txFrac = 0; txDueUs += 1; }
  }
}

// local playback: keep the earpiece buffer topped up from localPlayFn
static void runLocalPlayback() {
  if (!localPlayFn) return;
  while (jbCount() < LOCAL_FILL) {
    int16_t pcm[VOIP_FRAME_SAMPLES];
    int n = localPlayFn(pcm, VOIP_FRAME_SAMPLES);
    if (n <= 0) break;
    for (int i = 0; i < n; i++) jbPush(pcm[i]);
  }
}

