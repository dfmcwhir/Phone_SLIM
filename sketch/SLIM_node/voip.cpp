// ---------------------------------------------------------------------------
// G.711 u-law
// ---------------------------------------------------------------------------
static int16_t ulawDecodeTable[256];

static uint8_t linearToUlaw(int32_t pcm) {
  const int32_t BIAS = 0x84, CLIP = 32635;
  uint8_t sign = 0;
  if (pcm < 0) { pcm = -pcm; sign = 0x80; }
  if (pcm > CLIP) pcm = CLIP;
  pcm += BIAS;
  uint8_t exponent = 7;
  for (int32_t mask = 0x4000; exponent > 0 && !(pcm & mask); exponent--, mask >>= 1) {}
  uint8_t mantissa = (pcm >> (exponent + 3)) & 0x0F;
  return ~(sign | (exponent << 4) | mantissa);
}

static int16_t ulawToLinear(uint8_t u) {
  u = ~u;
  int32_t t = (((int32_t)(u & 0x0F) << 3) + 0x84) << ((u & 0x70) >> 4);
  return (u & 0x80) ? (int16_t)(0x84 - t) : (int16_t)(t - 0x84);
}

uint8_t voipLinearToUlaw(int32_t pcm) { return linearToUlaw(pcm); }
int16_t voipUlawToLinear(uint8_t u)   { return ulawDecodeTable[u]; }

// ---------------------------------------------------------------------------
// playback jitter buffer (loop task only)
// ---------------------------------------------------------------------------
#define JB_SIZE        4096                              // power of 2, 0.5 sec
#define JB_MASK        (JB_SIZE - 1)
#define JB_PREBUFFER   ((VOIP_JITTER_MS * VOIP_SAMPLE_RATE) / 1000)
#define JB_HIGH_WATER  (JB_PREBUFFER + 3 * VOIP_FRAME_SAMPLES)
#define JB_LOW_WATER   (JB_PREBUFFER / 2)
#define LOCAL_FILL     (JB_PREBUFFER + 2 * VOIP_FRAME_SAMPLES)   // local playback buffer target

static int16_t  jb[JB_SIZE];
static uint16_t jbHead = 0, jbTail = 0;
static bool     jbPlaying = false;
static bool     jbLocal = false;                // local playback: no prebuffering or drift correction
static uint8_t  jbDropCounter = 0;
static int16_t  upPrev = 0, upCur = 0;
static uint8_t  upPhase = 0;

// playback statistics (loop task)
static uint32_t stOutSamples = 0, stUnderruns = 0, stDrops = 0, stRepeats = 0;
static uint32_t stRxFrames = 0, stLost = 0, stLate = 0;
static uint16_t stJbMin = 0xFFFF, stJbMax = 0;
static int32_t  stRxPeak = 0;

static inline uint16_t jbCount() { return (jbHead - jbTail) & JB_MASK; }

static void jbReset() {
  jbHead = jbTail = 0;
  jbPlaying = false;
  jbDropCounter = 0;
  upPrev = upCur = 0;
  upPhase = 0;
}

static inline void jbPush(int16_t s) {
  if (jbCount() == JB_MASK) jbTail = (jbTail + 1) & JB_MASK;  // full: discard oldest
  jb[jbHead] = s;
  jbHead = (jbHead + 1) & JB_MASK;
}

static inline int16_t jbPop() {
  uint16_t count = jbCount();
  if (jbLocal) {                                 // local playback: just play what's there
    if (count == 0) return 0;
    int16_t s = jb[jbTail];
    jbTail = (jbTail + 1) & JB_MASK;
    return s;
  }
  if (!jbPlaying) {
    if (count < JB_PREBUFFER) return 0;          // still filling
    jbPlaying = true;
  }
  if (count < stJbMin) stJbMin = count;
  if (count > stJbMax) stJbMax = count;
  if (count == 0) {                              // underrun: refill before playing again
    jbPlaying = false;
    stUnderruns++;
    return 0;
  }
  // the two nodes' sample clocks never match exactly.  Gently drop or repeat
  // a sample now and then to keep the buffer near its target level.
  if (count > JB_HIGH_WATER && ++jbDropCounter >= 32) {
    jbDropCounter = 0;
    jbTail = (jbTail + 1) & JB_MASK;          // far end faster: skip a sample
    stDrops++;
  } else if (count < JB_LOW_WATER && ++jbDropCounter >= 32) {
    jbDropCounter = 0;
    stRepeats++;
    return jb[jbTail];                        // far end slower: repeat a sample
  }
  int16_t s = jb[jbTail];
  jbTail = (jbTail + 1) & JB_MASK;
  return s;
}

bool voipAudioActive() {
  return (sess == SS_CONNECTED && !sessTrunk) || localPlayFn != NULL;
}

// called by Mozzi updateAudio() at AUDIO_RATE.  Linear interpolation up to AUDIO_RATE.
int16_t voipNextPlaybackSample() {
  stOutSamples++;
  if (upPhase == 0) {
    upPrev = upCur;
    upCur = jbPop();
  }
  int32_t s = upPrev + (((int32_t)(upCur - upPrev) * upPhase) / VOIP_UPSAMPLE);
  if (++upPhase >= VOIP_UPSAMPLE) upPhase = 0;
  return (int16_t)s;
}

static int16_t lastFrame[VOIP_FRAME_SAMPLES];    // previous frame, replayed to cover lost packets

static void handleAudioPayload(uint16_t seq, const uint8_t* data, uint16_t len) {
  if (len > VOIP_FRAME_SAMPLES) len = VOIP_FRAME_SAMPLES;
  if (sessGotAudio) {
    int16_t gap = (int16_t)(seq - sessLastRxSeq);
    if (gap <= 0) { stLate++; return; }          // duplicate or late packet
    if (gap > 1) stLost += gap - 1;
    if (gap > 1 && gap <= 5) {                   // lost packets: replay last frame, fading out, to keep timing
      for (int f = 1; f < gap; f++) {
        for (int i = 0; i < VOIP_FRAME_SAMPLES; i++) {
          lastFrame[i] /= 2;
          jbPush(lastFrame[i]);
        }
        if (rxSinkFn) {                          // recording: lost audio becomes silence
          uint8_t silence[VOIP_FRAME_SAMPLES];
          memset(silence, 0xFF, sizeof(silence));
          rxSinkFn(silence, VOIP_FRAME_SAMPLES);
        }
      }
    }
  }
  sessGotAudio = true;
  sessLastRxSeq = seq;
  stRxFrames++;
  if (rxSinkFn) rxSinkFn(data, len);

  int32_t peak = 0;
  for (uint16_t i = 0; i < len; i++) {
    int32_t s = (int32_t)(ulawDecodeTable[data[i]] * VOIP_SPEAKER_GAIN);
    if (s > 32767) s = 32767; else if (s < -32768) s = -32768;
    lastFrame[i] = (int16_t)s;
    jbPush((int16_t)s);
    int32_t a = s < 0 ? -s : s;
    if (a > peak) peak = a;
  }
  farEndLevel = peak;
  if (peak > stRxPeak) stRxPeak = peak;
}

